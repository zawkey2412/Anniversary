const FILLED = new Set(['heart', 'play', 'pause', 'star', 'moon']);

export function icon(name, { size = '1em', fill = FILLED.has(name), stroke = 2, cls = '' } = {}) {
  const body = ICONS[name] || '';
  const paint = fill ? 'fill="currentColor" stroke="none"' : `fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round"`;
  return `<svg class="ic ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" ${paint} aria-hidden="true">${body}</svg>`;
}

// Replace every <i data-icon="name"> placeholder in the page.
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, { size: el.dataset.size || '1em', cls: el.className || '' });
  });
}
